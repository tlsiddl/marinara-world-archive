'use strict';
// Run with the real Marinara Engine image, isolated data, and a local fake provider.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const service = require('../world-archive/lib/service.cjs');
const { Archive } = require('../world-archive/lib/store.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wa-engine-test-'));
const store = new Archive(dir);
const world = store.createWorld({ name: '[시험] 세계' });
store.createEntity(world.worldId, { type: 'person', name: '[시험] Mira', fields: { hair: 'black', eyes: 'blue' } });
store.createEntity(world.worldId, { type: 'person', name: '[시험] Tovin', fields: { hair: 'blonde', eyes: 'green' } });
store.linkRoom('test-room', world.worldId);
service._test.useStore(store);
const context = { chatId: 'test-room', mainResponse: '§RP | 1 | 2 | 3 | 4§\n- [시험] Mira: coat | standing | calm\n- [시험] Tovin: coat | standing | calm', recentMessages: [], characters: [], memory: {}, streaming: false };
const config = { id: 'fake', name: '[시험] 삽화', type: 'illustrator', phase: 'post_processing', promptTemplate: 'Draw this scene.', settings: {} };
let calls = 0;
let captured = [];
const provider = { maxTokensOverrideValue: null, chatComplete: async (messages) => { calls++; captured = messages; return { content: '{"prompt":"test image","style":"test"}', usage: { totalTokens: 1 } }; } };
(async () => {
  await import(pathToFileURL('/app/packages/server/dist/routes/generate.routes.js').href);
  await import(pathToFileURL('/app/packages/server/dist/routes/generate/retry-agents-route.js').href);
  const { executeAgent } = await import(pathToFileURL('/app/packages/server/dist/services/agents/agent-executor.js').href);
  await executeAgent(config, context, provider, 'fake');
  assert.equal(calls, 1, 'the fake provider is called once');
  const text = captured.map((m) => m.content).join('\n');
  assert.match(text, /<world_archive_looks>/);
  assert.match(text, /black hair/);
  assert.match(text, /blue eyes/);
  assert.match(text, /blonde hair/);
  assert.match(text, /green eyes/);
  assert.equal(globalThis.__marinaraWorldArchive?.patches?.illustrator, 'ok');
  assert.equal(globalThis.__marinaraWorldArchive?.patches?.illustratorManual, 'ok');
  assert.equal(globalThis.__marinaraWorldArchive?.patches?.illustratorFix, 'ok');
  assert.equal(globalThis.__marinaraWorldArchive?.patches?.illustratorFixRetry, 'ok');
  const corrected = globalThis.__marinaraWorldArchive.illustratorFix('test-room', '@[시험] Mira, 1girl, blonde hair, green eyes | @[시험] Tovin, 1boy, black hair, blue eyes');
  assert.match(corrected, /black hair/);
  assert.match(corrected, /blonde hair/);
  assert.doesNotMatch(corrected, /@\[시험\]/);
  await executeAgent(config, { ...context, mainResponse: '[시험] Mira opens the door.' }, provider, 'fake');
  const plain = captured.map((m) => m.content).join('\n');
  assert.match(plain, /black hair/);
  assert.doesNotMatch(plain, /blonde hair/);
  await executeAgent(config, { ...context, chatId: 'not-linked' }, provider, 'fake');
  assert.doesNotMatch(captured.map((m) => m.content).join('\n'), /<world_archive_looks>/);
  globalThis.__shellWorldLooks = {};
  await executeAgent(config, context, provider, 'fake');
  assert.doesNotMatch(captured.map((m) => m.content).join('\n'), /<world_archive_looks>/);
  delete globalThis.__shellWorldLooks;
  assert.equal(calls, 4);
  console.log('실제 엔진: 인물 2명 · 카드 없는 방 · 미연결 방 · 셸 공존 통과 · 가짜 모델 4회');
})().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => fs.rmSync(dir, { recursive: true, force: true }));
